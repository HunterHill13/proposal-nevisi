def build_vancouver_entry(idx, r):
    authors = r.get('authors', [])
    if len(authors) > 6:
        author_str = ', '.join(authors[:6]) + ', et al.'
    elif authors:
        author_str = ', '.join(authors)
    else:
        author_str = 'Anon'
    
    title = (r.get('title') or '').rstrip('.')
    journal = (r.get('journal') or '').rstrip('.')
    year = r.get('year', 'NR')
    vol = r.get('volume') or ''
    issue = r.get('issue')
    iss_str = f"({issue})" if issue else ""
    pages = r.get('pages')
    pages_str = f":{pages}" if pages else ""
    doi = r.get('doi')
    doi_str = f" doi: {doi}." if doi else ""
    pmid = r.get('pmid')
    pmid_str = f" PMID: {pmid}." if pmid else ""

    return f"{idx}. {author_str}. {title}. {journal}. {year};{vol}{iss_str}{pages_str}.{doi_str}{pmid_str}".replace("..", ".")

